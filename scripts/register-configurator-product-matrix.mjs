function matrixSelectionEntry() {
  return {
    status: 'available',
    matrixId: profile.matrixId,
    assets: [],
  };
}

function availabilitySource(matrixIds) {
  const rows = matrixIds.map((matrixId) => `  '${matrixId}',`).join('\n');
  return `/**\n * Generated by scripts/register-configurator-product-matrix.mjs.\n *\n * A matrix is listed only after its complete inventory, proofs and responsive\n * light/dark asset family exist. Keeping activation separate from the planned\n * descriptors prevents an unfinished product from silently resolving to\n * missing files.\n */\nexport const AVAILABLE_CONFIGURATOR_MATRIX_IDS = Object.freeze([\n${rows}\n]);\n`;
}

function sameSet(actual, expected) {
  return JSON.stringify([...actual].sort()) === JSON.stringify([...expected].sort());
}

function sha256(buffer) {
  return createHash('sha256').update(buffer).digest('hex').toUpperCase();
}

function readUInt24LE(buffer, offset) {
  return buffer[offset] | (buffer[offset + 1] << 8) | (buffer[offset + 2] << 16);
}

function webpDimensions(buffer, label) {
  if (
    buffer.length < 20
    || buffer.toString('ascii', 0, 4) !== 'RIFF'
    || buffer.toString('ascii', 8, 12) !== 'WEBP'
  ) {
    throw new Error(`${label} is not a WebP RIFF file`);
  }

  let offset = 12;
  while (offset + 8 <= buffer.length) {
    const chunkType = buffer.toString('ascii', offset, offset + 4);
    const chunkSize = buffer.readUInt32LE(offset + 4);
    const data = offset + 8;

    if (chunkType === 'VP8X' && data + 10 <= buffer.length) {
      return {
        width: readUInt24LE(buffer, data + 4) + 1,
        height: readUInt24LE(buffer, data + 7) + 1,
      };
    }

    if (chunkType === 'VP8 ' && data + 10 <= buffer.length) {
      if (buffer[data + 3] !== 0x9d || buffer[data + 4] !== 0x01 || buffer[data + 5] !== 0x2a) {
        throw new Error(`${label} has an invalid VP8 frame header`);
      }
      return {
        width: buffer.readUInt16LE(data + 6) & 0x3fff,
        height: buffer.readUInt16LE(data + 8) & 0x3fff,
      };
    }

    if (chunkType === 'VP8L' && data + 5 <= buffer.length) {
      if (buffer[data] !== 0x2f) throw new Error(`${label} has an invalid VP8L signature`);
      const byte1 = buffer[data + 1];
      const byte2 = buffer[data + 2];
      const byte3 = buffer[data + 3];
      const byte4 = buffer[data + 4];
      return {
        width: 1 + byte1 + ((byte2 & 0x3f) << 8),
        height: 1 + ((byte2 & 0xc0) >> 6) + (byte3 << 2) + ((byte4 & 0x0f) << 10),
      };
    }

    offset = data + chunkSize + (chunkSize % 2);
  }

  throw new Error(`${label} has no supported WebP image chunk`);
}

function webpUsesAlpha(buffer, label) {
  if (
    buffer.length < 20
    || buffer.toString('ascii', 0, 4) !== 'RIFF'
    || buffer.toString('ascii', 8, 12) !== 'WEBP'
  ) {
    throw new Error(`${label} is not a WebP RIFF file`);
  }

  let offset = 12;
  let alphaFromExtendedHeader = false;
  while (offset + 8 <= buffer.length) {
    const chunkType = buffer.toString('ascii', offset, offset + 4);
    const chunkSize = buffer.readUInt32LE(offset + 4);
    const data = offset + 8;

    if (chunkType === 'ALPH') return true;
    if (chunkType === 'VP8X' && data < buffer.length) {
      alphaFromExtendedHeader = (buffer[data] & 0x10) !== 0;
    }
    if (chunkType === 'VP8L' && data + 5 <= buffer.length) {
      const losslessHeader = buffer.readUInt32LE(data + 1);
      return (losslessHeader & 0x10000000) !== 0;
    }

    offset = data + chunkSize + (chunkSize % 2);
  }
  return alphaFromExtendedHeader;
}

async function assetPixelMetrics(buffer) {
  const { data, info } = await sharp(buffer).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let alphaMin = 255;
  let alphaMax = 0;
  let left = info.width;
  let top = info.height;
  let right = -1;
  let bottom = -1;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      const alpha = data[(y * info.width + x) * 4 + 3];
      alphaMin = Math.min(alphaMin, alpha);
      alphaMax = Math.max(alphaMax, alpha);
      if (alpha <= 32) continue;
      left = Math.min(left, x);
      right = Math.max(right, x);
      top = Math.min(top, y);
      bottom = Math.max(bottom, y);
    }
  }
  if (right < 0) throw new Error('asset has no visible subject pixels');
  return {
    subjectThreshold: 32,
    alphaMin,
    alphaMax,
    subjectBounds: {
      leftSafetyPercent: Number(((left / info.width) * 100).toFixed(4)),
      rightSafetyPercent: Number((((info.width - right - 1) / info.width) * 100).toFixed(4)),
      topSafetyPercent: Number(((top / info.height) * 100).toFixed(4)),
      baselinePercent: Number(((bottom / info.height) * 100).toFixed(4)),
      subjectWidthPercent: Number((((right - left + 1) / info.width) * 100).toFixed(4)),
      subjectHeightPercent: Number((((bottom - top + 1) / info.height) * 100).toFixed(4)),
    },
  };
}

function publicAssetPath(assetPath, label) {
  if (typeof assetPath !== 'string' || !assetPath.startsWith('/assets/')) {
    throw new Error(`${label} must be an absolute /assets/ path`);
  }
  const resolved = path.resolve(PUBLIC_ROOT, assetPath.slice(1).split('/').join(path.sep));
  if (!resolved.startsWith(`${PUBLIC_ROOT}${path.sep}`)) {
    throw new Error(`${label} resolves outside the public asset root`);
  }
  return resolved;
}

async function preflightInventory(inventory, canonical) {
  if (inventory.schemaVersion !== 1) throw new Error('Inventory schemaVersion must be 1');
  if (inventory.id !== profile.matrixId || inventory.productId !== productId) {
    throw new Error(`Inventory identity does not match ${profile.matrixId}/${productId}`);
  }

  const expectedVariants = profile.fits.length * 2 * 2 * 2 * profile.finishes.length * 2;
  if (!Array.isArray(inventory.variants) || inventory.variants.length !== expectedVariants) {
    throw new Error(`Inventory has ${inventory.variants?.length || 0} variants; expected ${expectedVariants}`);
  }
  if (inventory.canvas?.width !== 1600 || inventory.canvas?.height !== 1067) {
    throw new Error('Inventory canvas must be 1600x1067');
  }
  if (!sameSet(inventory.dimensions?.themes || [], REQUIRED_THEMES)) {
    throw new Error('Inventory themes must be exactly light and dark');
  }
  if (!sameSet(inventory.dimensions?.widths || [], REQUIRED_WIDTHS)) {
    throw new Error('Inventory widths must be exactly 480, 960 and 1600');
  }
  for (const [dimension, expected] of Object.entries({
    brakes: ['power', 'disc'],
    fork: ['rigid', 'front'],
    drivetrain: ['single', '21'],
    finish: profile.finishes.map((finish) => finish.id),
    carrier: ['none', 'carrier'],
  })) {
    if (!sameSet(inventory.dimensions?.[dimension] || [], expected)) {
      throw new Error(`Inventory ${dimension} dimension does not match the exhaustive profile`);
    }
  }
  if (profile.fits.length > 1 && !sameSet(inventory.dimensions?.fit || [], profile.fits.map((fit) => fit.wheel))) {
    throw new Error('Inventory fit dimension does not match the product profile');
  }

  const expectedAssetKeys = REQUIRED_THEMES.flatMap((theme) => (
    REQUIRED_WIDTHS.map((width) => `${theme}:${width}`)
  ));
  const variantIds = new Set();
  const stateKeys = new Set();
  const assetPaths = new Set();

  for (const [variantIndex, variant] of inventory.variants.entries()) {
    const label = `inventory.variants[${variantIndex}]`;
    if (typeof variant.variant !== 'string' || !variant.variant) {
      throw new Error(`${label}.variant is required`);
    }
    if (variantIds.has(variant.variant)) throw new Error(`${label}.variant is duplicated`);
    variantIds.add(variant.variant);

    const stateKey = JSON.stringify({
      fitWheel: variant.stateCriteria?.fitWheel || null,
      components: variant.stateCriteria?.components || null,
      finishId: variant.stateCriteria?.finishId || null,
      accessories: [...(variant.stateCriteria?.accessories || [])].sort(),
    });
    if (stateKeys.has(stateKey)) throw new Error(`${label}.stateCriteria is duplicated`);
    stateKeys.add(stateKey);

    if (profile.fits.length > 1 && !profile.fits.some((fit) => fit.wheel === variant.stateCriteria?.fitWheel)) {
      throw new Error(`${label}.stateCriteria.fitWheel is outside the product profile`);
    }
    if (profile.fits.length === 1 && variant.stateCriteria?.fitWheel) {
      throw new Error(`${label}.stateCriteria.fitWheel must be omitted for a single-fit matrix`);
    }
    const componentDomains = {
      brakes: ['power-brake', 'disc-brake'],
      fork: ['rigid-fork', 'front-suspension'],
      drivetrain: ['single-speed', '21-speed'],
    };
    for (const [component, allowed] of Object.entries(componentDomains)) {
      if (!allowed.includes(variant.stateCriteria?.components?.[component])) {
        throw new Error(`${label}.stateCriteria.components.${component} is invalid`);
      }
    }
    if (!profile.finishes.some((finish) => finish.optionId === variant.stateCriteria?.finishId)) {
      throw new Error(`${label}.stateCriteria.finishId is invalid`);
    }
    const accessories = variant.stateCriteria?.accessories || [];
    if (
      !Array.isArray(accessories)
      || (accessories.length !== 0 && !(accessories.length === 1 && accessories[0] === 'ibc-carrier'))
    ) {
      throw new Error(`${label}.stateCriteria.accessories must be none or ibc-carrier`);
    }
    if (!Array.isArray(variant.assets) || variant.assets.length !== 6) {
      throw new Error(`${label}.assets must contain exactly 6 responsive assets`);
    }
    const actualAssetKeys = variant.assets.map((asset) => `${asset.theme}:${asset.width}`);
    if (!sameSet(actualAssetKeys, expectedAssetKeys)) {
      throw new Error(`${label}.assets must contain exactly 2 themes x 3 widths`);
    }

    for (const [assetIndex, asset] of variant.assets.entries()) {
      const assetLabel = `${label}.assets[${assetIndex}]`;
      if (!REQUIRED_THEMES.includes(asset.theme)) throw new Error(`${assetLabel}.theme is invalid`);
      if (!REQUIRED_WIDTHS.includes(asset.width)) throw new Error(`${assetLabel}.width is invalid`);
      if (asset.height !== EXPECTED_HEIGHTS[asset.width]) {
        throw new Error(`${assetLabel}.height must be ${EXPECTED_HEIGHTS[asset.width]}`);
      }
      if (assetPaths.has(asset.path)) throw new Error(`${assetLabel}.path is duplicated`);
      assetPaths.add(asset.path);
      if (!asset.path.startsWith(`/assets/configurator/v1/${productId}/side-r/`)) {
        throw new Error(`${assetLabel}.path is outside the ${productId} matrix asset family`);
      }

      const diskPath = publicAssetPath(asset.path, `${assetLabel}.path`);
      const buffer = await readFile(diskPath);
      const dimensions = webpDimensions(buffer, assetLabel);
      if (dimensions.width !== asset.width || dimensions.height !== asset.height) {
        throw new Error(
          `${assetLabel} is ${dimensions.width}x${dimensions.height}; expected ${asset.width}x${asset.height}`,
        );
      }
      if (!/^[A-F0-9]{64}$/.test(asset.sha256 || '')) {
        throw new Error(`${assetLabel}.sha256 is required as uppercase SHA-256`);
      }
      if (sha256(buffer) !== asset.sha256) {
        throw new Error(`${assetLabel}.sha256 differs from the inventory`);
      }
      if (asset.alphaMode !== 'transparent' || !webpUsesAlpha(buffer, assetLabel)) {
        throw new Error(`${assetLabel} must be an encoded transparent WebP`);
      }
      const metrics = await assetPixelMetrics(buffer);
      if (JSON.stringify(asset.pixelMetrics) !== JSON.stringify(metrics)) {
        throw new Error(`${assetLabel}.pixelMetrics do not match the encoded WebP`);
      }
      if (metrics.alphaMin !== 0 || metrics.alphaMax !== 255) {
        throw new Error(`${assetLabel} must retain a full 0..255 alpha range`);
      }
      const roundingEpsilon = 0.15;
      const bounds = metrics.subjectBounds;
      if (
        Math.abs(bounds.subjectWidthPercent - canonical.subjectWidthPercent.target)
          > canonical.subjectWidthPercent.tolerance + roundingEpsilon
      ) {
        throw new Error(`${assetLabel} violates the canonical subject-width contract`);
      }
      if (
        Math.abs(bounds.baselinePercent - canonical.baselinePercent.target)
          > canonical.baselinePercent.tolerance + roundingEpsilon
      ) {
        throw new Error(`${assetLabel} violates the canonical baseline contract`);
      }
      if (
        bounds.topSafetyPercent + roundingEpsilon < canonical.safetyPercent.top
        || bounds.leftSafetyPercent + roundingEpsilon < canonical.safetyPercent.left
        || bounds.rightSafetyPercent + roundingEpsilon < canonical.safetyPercent.right
      ) {
        throw new Error(`${assetLabel} violates the canonical safety-margin contract`);
      }
    }
  }

  return { expectedVariants, responsiveAssets: assetPaths.size };
}

function preflightRuntimeStates(inventory, runtime, sourceSkuIds) {
  const skusById = new Map(runtime.configuratorCatalog.skus.map((sku) => [sku.id, sku]));
  for (const variant of inventory.variants) {
    let build = runtime.createDefaultBuild({ modelId: productId });
    if (variant.stateCriteria?.fitWheel) {
      const fitSkuId = sourceSkuIds.find((skuId) => (
        skusById.get(skuId)?.wheel === variant.stateCriteria.fitWheel
      ));
      if (!fitSkuId) throw new Error(`${variant.variant} has no runtime SKU for its fit`);
      build = runtime.selectBuildOption(build, 'fit', fitSkuId);
    }
    for (const [group, optionId] of Object.entries(variant.stateCriteria.components)) {
      build = runtime.selectBuildOption(build, 'ride-setup', optionId, group);
    }
    build = runtime.selectBuildOption(build, 'finish', variant.stateCriteria.finishId);
    build = runtime.selectBuildOption(
      build,
      'accessories',
      variant.stateCriteria.accessories.includes('ibc-carrier') ? 'ibc-carrier' : 'none',
    );

    const resolved = runtime.resolveBuild(build).build;
    const expected = {
      fitWheel: variant.stateCriteria.fitWheel || profile.fits[0].wheel,
      components: variant.stateCriteria.components,
      finishId: variant.stateCriteria.finishId,
      accessories: [...variant.stateCriteria.accessories].sort(),
    };
    const actual = {
      fitWheel: resolved.fit.wheel,
      components: resolved.components,
      finishId: resolved.finish,
      accessories: [...resolved.accessories].sort(),
    };
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
      throw new Error(`${variant.variant} cannot be reached through the runtime selection API`);
    }
  }
}

function availabilityMatrixIds(source) {
  return [...source.matchAll(/^\s*'([^']+)',?\s*$/gm)].map((match) => match[1]);
}

async function withActivationLock(callback) {
  let lock;
  try {
    lock = await open(ACTIVATION_LOCK_PATH, 'wx');
    await lock.writeFile(`${process.pid}\n`);
  } catch (error) {
    if (lock) {
      await lock.close().catch(() => {});
      await rm(ACTIVATION_LOCK_PATH, { force: true }).catch(() => {});
    }
    throw new Error(`Another matrix registration may be running (${error.code || error.message})`);
  }

  try {
    return await callback();
  } finally {
    await lock.close().catch(() => {});
    await rm(ACTIVATION_LOCK_PATH, { force: true }).catch(() => {});
  }
}

async function writeActivationTransaction(entries, expectedOriginals) {
  const token = `${process.pid}-${Date.now()}`;
  const staged = entries.map(({ target, content }) => ({
    target,
    content,
    temp: `${target}.tmp-${token}`,
    backup: `${target}.bak-${token}`,
    installed: false,
    backedUp: false,
  }));

  try {
    for (const item of staged) {
      await writeFile(item.temp, item.content, { flag: 'wx' });
    }

    // Fail if another process changed either activation file after this script
    // constructed the new pair. This avoids committing against stale state.
    for (const item of staged) {
      const current = await readFile(item.target, 'utf8');
      if (current !== expectedOriginals.get(item.target)) {
        throw new Error(`${path.relative(REPO_ROOT, item.target)} changed during registration`);
      }
      await copyFile(item.target, item.backup);
      item.backedUp = true;
    }

    for (const item of staged) {
      await rename(item.temp, item.target);
      item.installed = true;
    }
  } catch (error) {
    const rollbackErrors = [];
    for (const item of [...staged].reverse()) {
      let preserveBackup = false;
      try {
        if (item.installed) {
          await rm(item.target, { force: true });
          await rename(item.backup, item.target);
          item.backedUp = false;
        }
      } catch (rollbackError) {
        preserveBackup = true;
        rollbackErrors.push(`${path.relative(REPO_ROOT, item.target)}: ${rollbackError.message}`);
      }
      await rm(item.temp, { force: true }).catch(() => {});
      if (!preserveBackup) await rm(item.backup, { force: true }).catch(() => {});
    }
    const rollbackMessage = rollbackErrors.length > 0
      ? ` Rollback also failed: ${rollbackErrors.join('; ')}`
      : '';
    throw new Error(`Activation transaction failed: ${error.message}.${rollbackMessage}`);
  }

  for (const item of staged) await rm(item.backup, { force: true });
}

await access(inventoryPath);
await access(generationRecordPath);

const [manifestSource, availabilityOriginal, inventory, generationProof, runtime] = await Promise.all([
  readFile(MANIFEST_PATH, 'utf8'),
  readFile(AVAILABILITY_PATH, 'utf8'),
  readFile(inventoryPath, 'utf8').then(JSON.parse),
  readFile(generationRecordPath, 'utf8').then(JSON.parse),
  import(pathToFileURL(CONFIGURATOR_MODULE).href),
]);
const manifest = JSON.parse(manifestSource);

if (generationProof.matrixId !== profile.matrixId || generationProof.productId !== productId) {
  throw new Error(`Generation record identity does not match ${profile.matrixId}/${productId}`);
}

const preflight = await preflightInventory(inventory, manifest.canonical);

const product = manifest.products.find((candidate) => candidate.productId === productId);
if (!product) throw new Error(`${productId} product not found in configurator manifest`);
if ((manifest.visualMatrices || []).some((candidate) => (
  candidate.productId === productId && candidate.id !== profile.matrixId
))) {
  throw new Error(`${productId} is already registered to a different visual matrix`);
}

const sourceSkuIds = runtime.configuratorCatalog.skus
  .filter((sku) => sku.modelId === productId)
  .map((sku) => sku.id);
if (!sourceSkuIds.length) throw new Error(`No runtime SKUs found for ${productId}`);
for (const fit of profile.fits) {
  if (!sourceSkuIds.some((skuId) => runtime.configuratorCatalog.skus.find((sku) => sku.id === skuId)?.wheel === fit.wheel)) {
    throw new Error(`No runtime SKU found for ${productId} fit ${fit.wheel}`);
  }
}
preflightRuntimeStates(inventory, runtime, sourceSkuIds);

if (preflightOnly) {
  console.log(
    `Preflight passed for ${profile.matrixId}: ${preflight.expectedVariants} variants, ${preflight.responsiveAssets} responsive assets.`,
  );
  process.exit(0);
}

const matrix = {
  id: profile.matrixId,
  productId,
  status: 'available',
  authorityTier: 'C',
  provenanceStatus: 'ai-assisted-exhaustive-component-preview-product-owner-review-required',
  role: 'poster',
  canvasConformance: 'canonical',
  sourceSkuIds,
  inventoryPath: inventoryPublicPath,
  generationRecord,
  dimensions: {
    ...(profile.fits.length > 1 ? { fit: profile.fits.map((fit) => fit.wheel) } : {}),
    brakes: ['power-brake', 'disc-brake'],
    fork: ['rigid-fork', 'front-suspension'],
    drivetrain: ['single-speed', '21-speed'],
    finish: profile.finishes.map((finish) => finish.optionId),
    accessories: ['none', 'ibc-carrier'],
    themes: ['light', 'dark'],
    widths: [480, 960, 1600],
  },
};

manifest.visualMatrices = (manifest.visualMatrices || []).filter((candidate) => candidate.id !== profile.matrixId);
manifest.visualMatrices.push(matrix);
product.selectionDependent = Object.fromEntries(
  ['fit', 'brakes', 'fork', 'drivetrain', 'finish', 'accessories']
    .map((selectionClass) => [selectionClass, matrixSelectionEntry()]),
);

const availableMatrixIds = manifest.visualMatrices
  .filter((candidate) => candidate.status === 'available')
  .map((candidate) => candidate.id);

const originalAvailabilityIds = availabilityMatrixIds(availabilityOriginal);
const wasInManifest = (JSON.parse(manifestSource).visualMatrices || [])
  .some((candidate) => candidate.id === profile.matrixId);
const wasAvailable = originalAvailabilityIds.includes(profile.matrixId);
if (wasAvailable && !wasInManifest) {
  throw new Error(`${profile.matrixId} is available without a matching manifest matrix`);
}

const nextManifestSource = `${JSON.stringify(manifest, null, 2)}\n`;
const nextAvailabilitySource = availabilitySource(availableMatrixIds);
if (wasAvailable) {
  if (manifestSource === nextManifestSource && availabilityOriginal === nextAvailabilitySource) {
    console.log(`${profile.matrixId} is already registered and passed the complete preflight.`);
    process.exit(0);
  }
  throw new Error(`${profile.matrixId} is already active with different registration data; refusing an in-place partial update`);
}

await withActivationLock(() => writeActivationTransaction(
  [
    // Manifest first, availability last: an interrupted first-time write never
    // exposes the new matrix through the runtime activation gate.
    { target: MANIFEST_PATH, content: nextManifestSource },
    { target: AVAILABILITY_PATH, content: nextAvailabilitySource },
  ],
  new Map([
    [MANIFEST_PATH, manifestSource],
    [AVAILABILITY_PATH, availabilityOriginal],
  ]),
));

console.log(
  `Registered and activated ${profile.matrixId} for ${sourceSkuIds.length} SKU(s) after validating ${preflight.responsiveAssets} responsive assets.`,
);
